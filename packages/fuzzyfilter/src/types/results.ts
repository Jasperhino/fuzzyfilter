/**
 * Formats a single FilterSuggestion as a one-line string.
 * Shows all key fields in a compact, readable format.
 */
export function formatSuggestion(s: FilterSuggestion): string {
  const parts: string[] = [];

  // Score (percentage)
  parts.push(`[${(s.score * 100).toFixed(1)}%]`);

  // Completeness indicator
  parts.push(s.isComplete ? "✓" : "○");

  // Label
  parts.push(`"${s.label}"`);

  // Field → Operator
  const resolution: string[] = [];
  if (s.fieldKey) resolution.push(s.fieldKey);
  if (s.operatorId) resolution.push(s.operatorId);
  if (resolution.length > 0) {
    parts.push(`(${resolution.join(" → ")})`);
  }

  // Overloads
  if (s.overloadIds && s.overloadIds.length > 0) {
    parts.push(`overloads:[${s.overloadIds.join(", ")}]`);
  }

  // Matches summary
  if (s.matches && s.matches.length > 0) {
    const matchSummary = s.matches
      .map((m) => `${m.text}→${m.resolvedTo}`)
      .join(", ");
    parts.push(`matches:{${matchSummary}}`);
  }

  // Parsed values summary
  if (s.parsedValues && s.parsedValues.length > 0) {
    const valueSummary = s.parsedValues
      .map((pv) => formatParsedValueCompact(pv))
      .join(", ");
    parts.push(`values:{${valueSummary}}`);
  }

  // Score breakdown
  if (s.scoreBreakdown) {
    const sb = s.scoreBreakdown;
    const factors: string[] = [];
    if (sb.chunking !== 1) factors.push(`chk:${(sb.chunking * 100).toFixed(0)}%`);
    if (sb.field !== 1) factors.push(`fld:${(sb.field * 100).toFixed(0)}%`);
    if (sb.operator !== 1) factors.push(`op:${(sb.operator * 100).toFixed(0)}%`);
    if (sb.valueParse !== 1) factors.push(`val:${(sb.valueParse * 100).toFixed(0)}%`);
    if (sb.completeness !== 1) factors.push(`cmp:${(sb.completeness * 100).toFixed(0)}%`);
    if ("coherence" in sb && (sb as any).coherence !== 1) {
      factors.push(`coh:${((sb as any).coherence * 100).toFixed(0)}%`);
    }
    if (factors.length > 0) {
      parts.push(`breakdown:{${factors.join(", ")}}`);
    }
  }

  // Chunking
  if (s.chunking) {
    const chunks = s.chunking.chunks.map((c) => `"${c.text}"`).join("|");
    parts.push(`chunks:[${chunks}]`);
  }

  // Remaining
  if (s.remaining) {
    parts.push(`remaining:"${s.remaining}"`);
  }

  return parts.join(" ");
}

/**
 * Formats a parsed value compactly.
 */
function formatParsedValueCompact(pv: ParsedValue): string {
  const val = pv.value;
  if (typeof val === "object" && val !== null && "value" in val) {
    const numVal = val as { value: number; unit?: { id: string }; dimension?: string };
    if (numVal.unit) {
      return `${numVal.value}${numVal.unit.id}`;
    }
    if (numVal.dimension) {
      return `${numVal.value}(${numVal.dimension})`;
    }
    return String(numVal.value);
  }
  return pv.rawText;
}

/**
 * Formats a SuggestionResponse with all suggestions, one per line.
 */
export function formatResponse(r: SuggestionResponse): string {
  const lines: string[] = [];

  // Header
  lines.push(`═══ Query: "${r.query}" (cursor: ${r.cursorPosition}) ═══`);
  lines.push(`Found ${r.suggestions.length} suggestions in ${r.responseTimeMs?.toFixed(2) ?? "?"}ms`);
  lines.push("");

  // Each suggestion on its own line
  for (let i = 0; i < r.suggestions.length; i++) {
    const suggestion = r.suggestions[i];
    if (suggestion) {
      lines.push(`${(i + 1).toString().padStart(2)}. ${formatSuggestion(suggestion)}`);
    }
  }

  return lines.join("\n");
}
