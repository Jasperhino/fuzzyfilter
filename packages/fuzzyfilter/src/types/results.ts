// ============================================================================
// TAB COMPLETION
// ============================================================================

/**
 * Tab completion for the token at the cursor position.
 * 
 * This provides a simple text edit to complete the current word,
 * similar to shell tab completion. Apply by pressing Tab.
 * 
 * @example
 * User types: "wat|" (cursor at end)
 * TabCompletion: { original: "wat", completion: "water", range: { start: 0, end: 3 } }
 * Result after Tab: "water|"
 */
export interface TabCompletion {
  /**
   * The original text that was matched.
   */
  original: string;

  /**
   * The completed text to insert.
   */
  completion: string;

  /**
   * The range in the query to replace.
   */
  range: {
    /** Start position (inclusive) */
    start: number;
    /** End position (exclusive) */
    end: number;
  };

  /**
   * Match score (0-1, higher is better).
   */
  score: number;

  /**
   * What type of thing was matched.
   */
  matchType: "field" | "operator" | "value" | "unit";

  /**
   * Additional context about the match.
   */
  context?: {
    /** For value matches, which field it belongs to */
    fieldKey?: string;
    /** For operator matches, the operator ID */
    operatorId?: string;
  };
}


// ============================================================================
// SUGGESTION RESULT
// ============================================================================

/**
 * A single filter suggestion to display to the user.
 * 
 * Generated by the beam search engine, includes full details about
 * how the query was parsed and matched.
 */
export interface FilterSuggestion {
  /** Human-readable label (e.g., "Status equals Open") */
  label: string;

  /** Alternative display label */
  displayLabel?: string;

  /** Score for ranking (higher = better, range [0,1]) */
  score: number;

  /** Is this a complete, executable filter? */
  isComplete: boolean;

  /** Category for grouping suggestions */
  category?: "field" | "operator" | "value";

  /** Number of rows matching this filter (if known) */
  resultCount?: number;

  /** Resolved field key */
  fieldKey?: string;

  /** Resolved operator ID */
  operatorId?: string;

  /** Matched overload IDs that could apply */
  overloadIds?: string[];

  /** 
   * How the query was chunked/tokenized.
   * Shows the strategy used and plausibility score.
   */
  chunking?: Chunking;

  /**
   * Detailed matches showing what each query part resolved to.
   * Each match includes the original text, what it matched to,
   * the score, and character indexes for highlighting.
   */
  matches?: ParseMatch[];

  /**
   * Parsed values extracted from the query.
   * May include unit information.
   */
  parsedValues?: ParsedValue[];

  /**
   * Breakdown of score factors for debugging/visualization.
   * Shows how chunking, field, operator, value, and completeness
   * contributed to the final score.
   */
  scoreBreakdown?: ScoreBreakdown & { final: number };

  /** Unparsed remaining text */
  remaining?: string;

  /**
   * Tab completion for this suggestion.
   * 
   * Shows what text edit would happen if the user presses Tab
   * while this suggestion is highlighted. Based on what this
   * suggestion matched in the query.
   * 
   * Only present when `enableAutocomplete` is true in config.
   */
  tabCompletion?: TabCompletion;

  /** Additional metadata */
  metadata?: Record<string, unknown>;
}

// ============================================================================
// SUGGESTION RESPONSE
// ============================================================================

/**
 * Complete response from the suggestion engine
 */
export interface SuggestionResponse {
  /** Original query */
  query: string;

  /** Cursor position in query */
  cursorPosition: number;

  /** Top suggestions (ranked by score) */
  suggestions: FilterSuggestion[];

  /** Time taken to generate suggestions (ms) */
  responseTimeMs?: number;
}

